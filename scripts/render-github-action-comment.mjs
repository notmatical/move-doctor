// Comment structure and several helpers are adapted from react-doctor's
// scripts/render-github-action-comment.mjs:
//   https://github.com/millionco/react-doctor (MIT License, © Aiden Bai)
// Reworked for move-doctor's canonical report shape, citations, and the
// annotation + fail-on handling its CLI doesn't provide.

import fs from "node:fs";
import path from "node:path";

const MARKER = "<!-- move-doctor:summary -->";
const BRAND_LINK_URL = "https://move.doctor";
const BUG_REPORT_URL = "https://github.com/notmatical/move-doctor";
const BRAND_HEADER = `### [Move Doctor](${BRAND_LINK_URL}) — a deterministic linter for Sui Move`;
const BRAND_FOOTER = `Generated by [Move Doctor](${BRAND_LINK_URL}). Every rule cites its source.`;
const TOP_RULE_LIMIT = 5;

const [reportPath, commentPath] = process.argv.slice(2);

const pluralize = (count, singular, plural = `${singular}s`) =>
  `${count} ${count === 1 ? singular : plural}`;

const escapeCell = (value) =>
  String(value ?? "")
    .replaceAll("|", "\\|")
    .replaceAll("\n", " ");

const appendOutput = (name, value) => {
  const outputPath = process.env.GITHUB_OUTPUT;
  if (!outputPath) return;
  fs.appendFileSync(outputPath, `${name}=${value ?? ""}\n`);
};

const appendSummary = (body) => {
  const summaryPath = process.env.GITHUB_STEP_SUMMARY;
  if (!summaryPath) return;
  fs.appendFileSync(summaryPath, `${body}\n`);
};

const readReport = () => {
  if (!reportPath) throw new Error("Missing report path.");
  return JSON.parse(fs.readFileSync(reportPath, "utf8"));
};

const renderLines = (lines) =>
  lines
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trimEnd();

const buildBugReportUrl = (report) => {
  const runUrl = process.env.GITHUB_RUN_URL;
  const message =
    report.error?.message ?? "Move Doctor failed before completing the scan.";
  const bodyLines = [
    "Move Doctor Action failed before completing a scan.",
    "",
    "### Error",
    "",
    `\`${message}\``,
    "",
    runUrl ? `- Workflow run: ${runUrl}` : null,
  ].filter(Boolean);
  const parameters = new URLSearchParams({
    title: "Move Doctor Action failed",
    body: bodyLines.join("\n"),
  });
  return `${BUG_REPORT_URL}/issues/new?${parameters.toString()}`;
};

const formatScore = (summary) => {
  if (typeof summary?.score !== "number") return "Unavailable";
  const label =
    typeof summary.scoreLabel === "string" ? ` (${summary.scoreLabel})` : "";
  return `${summary.score} / 100${label}`;
};

const formatScope = () => {
  const diff = process.env.INPUT_DIFF;
  if (!diff || diff === "false") return "Full project";
  if (diff === "true") return "Changed files vs `HEAD`";
  return `Changed files vs \`${diff}\``;
};

const hasIncompleteChecks = (report) => report.compilerLintAvailable === false;

const buildStatusLine = (report) => {
  const summary = report.summary ?? {};
  const totalIssues = summary.totalDiagnosticCount ?? 0;
  if (totalIssues === 0 && hasIncompleteChecks(report)) {
    return "No Move Doctor findings, but some checks were incomplete.";
  }
  if (totalIssues === 0) return "No Move Doctor findings in this scan.";
  return `Move Doctor found ${pluralize(totalIssues, "finding")} in ${pluralize(summary.affectedFileCount ?? 0, "file")}.`;
};

const groupDiagnosticsByRule = (diagnostics) => {
  const groups = new Map();
  for (const diagnostic of diagnostics ?? []) {
    const group = groups.get(diagnostic.ruleId) ?? {
      ruleId: diagnostic.ruleId,
      severity: diagnostic.severity,
      category: diagnostic.bucket,
      citationUrl: diagnostic.citationUrl,
      count: 0,
    };
    group.count += 1;
    if (diagnostic.severity === "error") group.severity = "error";
    groups.set(diagnostic.ruleId, group);
  }
  const rank = (severity) =>
    severity === "error" ? 0 : severity === "warning" ? 1 : 2;
  return [...groups.values()].sort((a, b) => {
    const severityDelta = rank(a.severity) - rank(b.severity);
    if (severityDelta !== 0) return severityDelta;
    return b.count - a.count;
  });
};

const buildTopRulesSection = (diagnostics) => {
  const groups = groupDiagnosticsByRule(diagnostics).slice(0, TOP_RULE_LIMIT);
  if (groups.length === 0) return "";
  const lines = [
    "### Top Findings",
    "",
    "| Rule | Severity | Category | Count |",
    "| --- | --- | --- | ---: |",
  ];
  for (const group of groups) {
    const rule = group.citationUrl
      ? `[\`${escapeCell(group.ruleId)}\`](${group.citationUrl})`
      : `\`${escapeCell(group.ruleId)}\``;
    lines.push(
      `| ${rule} | ${escapeCell(group.severity)} | ${escapeCell(group.category)} | ${group.count} |`,
    );
  }
  return `${lines.join("\n")}\n\n`;
};

const buildIncompleteChecksSection = (report) => {
  if (!hasIncompleteChecks(report)) return "";
  return `${[
    "### Incomplete Checks",
    "",
    "- `compiler/*` (`W0xxxx`): the Sui CLI was not found on `PATH`, so compiler lints were skipped. Set the `sui-version` input to enable them.",
  ].join("\n")}\n\n`;
};

const buildErrorBody = (report) => {
  const message =
    report.error?.message ?? "Move Doctor failed before completing the scan.";
  const runUrl = process.env.GITHUB_RUN_URL;
  return renderLines([
    MARKER,
    BRAND_HEADER,
    "",
    "Move Doctor could not complete this scan.",
    "",
    `> ${message}`,
    "",
    runUrl ? `[View workflow run](${runUrl})` : "",
    `[Report this bug](${buildBugReportUrl(report)})`,
    "",
    BRAND_FOOTER,
    "",
  ]);
};

const buildCommentBody = (report) => {
  if (!report.ok) return buildErrorBody(report);

  const summary = report.summary ?? {};
  const totalIssues = summary.totalDiagnosticCount ?? 0;
  const runUrl = process.env.GITHUB_RUN_URL;

  const lines = [
    MARKER,
    BRAND_HEADER,
    "",
    buildStatusLine(report),
    "",
    "| Score | Issues | Errors | Warnings | Affected Files | Scope |",
    "| --- | ---: | ---: | ---: | ---: | --- |",
    `| ${escapeCell(formatScore(summary))} | ${totalIssues} | ${summary.errorCount ?? 0} | ${summary.warningCount ?? 0} | ${summary.affectedFileCount ?? 0} | ${escapeCell(formatScope())} |`,
    "",
    buildTopRulesSection(report.diagnostics),
    buildIncompleteChecksSection(report),
    runUrl ? `[View workflow run](${runUrl})` : "",
    "",
    BRAND_FOOTER,
    "",
  ];

  return renderLines(lines);
};

const report = readReport();
const body = buildCommentBody(report);

if (commentPath) {
  fs.writeFileSync(commentPath, body.endsWith("\n") ? body : `${body}\n`);
} else {
  process.stdout.write(body.endsWith("\n") ? body : `${body}\n`);
}
appendSummary(body);

appendOutput(
  "score",
  typeof report.summary?.score === "number" ? String(report.summary.score) : "",
);
appendOutput("total-issues", String(report.summary?.totalDiagnosticCount ?? 0));
appendOutput("error-count", String(report.summary?.errorCount ?? 0));
appendOutput("warning-count", String(report.summary?.warningCount ?? 0));
appendOutput("info-count", String(report.summary?.infoCount ?? 0));
appendOutput("affected-files", String(report.summary?.affectedFileCount ?? 0));

// --- move-doctor-specific: annotations + fail decision -------------------

const workspaceDir = process.env.GITHUB_WORKSPACE || process.cwd();

const relativePath = (filePath) => {
  if (!filePath) return filePath;
  const rel = path.relative(workspaceDir, filePath);
  if (!rel || rel.startsWith("..") || path.isAbsolute(rel)) {
    return String(filePath).replaceAll("\\", "/");
  }
  return rel.replaceAll("\\", "/");
};

const escapeData = (text) =>
  String(text)
    .replaceAll("%", "%25")
    .replaceAll("\r", "%0D")
    .replaceAll("\n", "%0A");

const escapeProp = (text) =>
  escapeData(text).replaceAll(":", "%3A").replaceAll(",", "%2C");

if (process.env.INPUT_ANNOTATIONS === "true" && report.ok) {
  for (const d of report.diagnostics ?? []) {
    const command =
      d.severity === "error"
        ? "error"
        : d.severity === "warning"
          ? "warning"
          : "notice";
    const title = d.citation ? `${d.ruleId} — ${d.citation}` : d.ruleId;
    const props = [
      `file=${escapeProp(relativePath(d.filePath))}`,
      `line=${d.line ?? 1}`,
      `col=${d.column ?? 1}`,
      `title=${escapeProp(title)}`,
    ].join(",");
    process.stdout.write(`::${command} ${props}::${escapeData(d.message)}\n`);
  }
}

const decideFail = () => {
  if (!report.ok) return true;
  const failOn = (process.env.INPUT_FAIL_ON || "error").toLowerCase();
  if (failOn === "none") return false;
  const errors = report.summary?.errorCount ?? 0;
  const warnings = report.summary?.warningCount ?? 0;
  if (failOn === "warning") return errors + warnings > 0;
  return errors > 0;
};

appendOutput("should-fail", decideFail() ? "true" : "false");
